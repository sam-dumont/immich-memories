/** A section's name, in the reader's language. */
export const sectionLabel = (name: string) => (SECTIONS[name] ? t(SECTIONS[name]) : name.replaceAll('_', ' '));

/** A setting's name, in the reader's language; `key` is the server's `section.name`. */
export const settingLabel = (key: string) => (SETTINGS[key] ? t(SETTINGS[key]) : key.slice(key.indexOf('.') + 1));
